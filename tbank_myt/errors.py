"""Типы ошибок MyT.

В банковском репозитории эти классы жили в client.py и различались по одной
причине: `SessionExpired` там отделял «сессию можно починить refresh-ом» от
«запрос не прошёл». Здесь продукт один, поэтому и иерархия плоская: всё, что
пришло от сервиса, — `MytApiError`, а мёртвая сессия — его частный случай.

Имена местные намеренно. Модуль, называющий свою ошибку `TbankApiError`, обещает
родство с банковским MCP, которого больше нет: сессии разные, хосты разные,
чинятся они по-разному, и ловить их одним `except` — ошибка, которую лучше
сделать невозможной."""
from __future__ import annotations


class MytApiError(RuntimeError):
    def __init__(self, code: str, message: str):
        super().__init__(f"{code}: {message}")
        self.result_code = code
        self.message = message


class MytSessionExpired(MytApiError):
    """Корпоративный токен мёртв: refresh не поможет, нужен полный вход.

    Отдельный тип, потому что развилка здесь ровно одна и она дорогая: всё
    остальное лечится повтором, а это — только `login_cli.py`, то есть паролем и
    SMS, которых у агента нет и не будет."""
